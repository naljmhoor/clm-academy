import { useEffect, useRef, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { create } from 'zustand';
import clsx from 'clsx';
import { ArrowLeft, BookOpen, CircleAlert, FileText, Loader2, MessageCircleQuestion, PlayCircle, Send, Trash2, X } from 'lucide-react';
import { useClm } from '@/store/caseStore';
import { routeContext, useAcademy } from '../academyStore';
import { articleById } from '../knowledge/articles';
import { ArticleView } from '../knowledge/ArticleView';
import { startTour } from '../tours/TourHost';
import { ask, assistantMode } from './client';
import { suggestedQuestions, type AssistantAction, type AssistantAnswer } from './engine';

interface Msg {
  id: number;
  role: 'user' | 'assistant';
  text: string;
  answer?: AssistantAnswer;
}

/** Conversation survives closing and reopening the panel (not persisted across reloads). */
const useConversation = create<{ msgs: Msg[]; push: (m: Omit<Msg, 'id'>) => void; clear: () => void }>((set) => ({
  msgs: [],
  push: (m) => set((s) => ({ msgs: [...s.msgs, { ...m, id: Date.now() + Math.random() }] })),
  clear: () => set({ msgs: [] }),
}));

export function AssistantPanel() {
  const open = useAcademy((s) => s.assistantOpen);
  if (!open) return null;
  return <Panel />;
}

function Panel() {
  const { closeAssistant, assistantArticle, openAssistant, location } = useAcademy();
  const ctx = routeContext(location);
  const c = useClm((s) => (ctx.caseId ? s.cases.find((x) => x.id === ctx.caseId) : undefined));
  const { msgs, push, clear } = useConversation();
  const [text, setText] = useState('');
  const [busy, setBusy] = useState(false);
  const navigate = useNavigate();
  const listRef = useRef<HTMLDivElement>(null);
  const article = assistantArticle ? articleById(assistantArticle) : undefined;

  useEffect(() => {
    listRef.current?.scrollTo({ top: listRef.current.scrollHeight, behavior: 'smooth' });
  }, [msgs.length, busy]);

  const send = async (q: string) => {
    const question = q.trim();
    if (!question || busy) return;
    setText('');
    push({ role: 'user', text: question });
    setBusy(true);
    const answer = await ask(question, ctx, c);
    setBusy(false);
    push({ role: 'assistant', text: answer.answer, answer });
  };

  const runAction = (a: AssistantAction) => {
    if (a.articleId) openAssistant(a.articleId);
    else if (a.tourId) {
      closeAssistant();
      startTour(a.tourId);
    } else if (a.route) navigate(a.route);
  };

  const contextLabel = c ? `Viewing ${c.id}${ctx.tab ? ` · ${ctx.tab}` : ''}` : ctx.module === 'case-queue' ? 'Viewing the Case Queue' : ctx.module === 'entities' ? 'Viewing Entities' : 'CLM Academy';

  return (
    <aside data-training-layer aria-label="Ask CLM" className="fixed bottom-0 right-0 top-9 z-[58] flex w-[420px] flex-col border-l border-academy/20 bg-white shadow-pop">
      <div className="flex items-center gap-2 border-b border-line px-4 py-3">
        <MessageCircleQuestion className="h-5 w-5 text-academy" />
        <div className="flex-1">
          <div className="text-sm font-semibold">Ask CLM</div>
          <div className="text-2xs text-ink-muted">{contextLabel}</div>
        </div>
        {msgs.length > 0 && !article && (
          <button type="button" onClick={clear} aria-label="Clear conversation" title="Clear conversation" className="rounded p-1 text-ink-muted hover:bg-surface-sunken">
            <Trash2 className="h-4 w-4" />
          </button>
        )}
        <button type="button" onClick={closeAssistant} aria-label="Close Ask CLM" className="rounded p-1 text-ink-muted hover:bg-surface-sunken">
          <X className="h-4 w-4" />
        </button>
      </div>
      <div className={clsx('px-4 py-1.5 text-2xs', assistantMode === 'ai' ? 'bg-green-50 text-green-800' : 'bg-academy-soft text-academy')}>
        {assistantMode === 'ai'
          ? 'Connected to the CLM AI service · answers are grounded in approved documentation.'
          : 'Knowledge search mode · answers are retrieved from the CLM knowledge base and the current case, not generated by AI.'}
      </div>

      {article ? (
        <div className="flex-1 overflow-y-auto px-4 py-3">
          <button type="button" onClick={() => openAssistant(null)} className="mb-3 flex items-center gap-1 text-xs font-medium text-academy hover:underline">
            <ArrowLeft className="h-3.5 w-3.5" />
            Back to conversation
          </button>
          <ArticleView
            compact
            a={article}
            onOpenArticle={(id) => openAssistant(id)}
            onStartTour={(id) => {
              closeAssistant();
              startTour(id);
            }}
          />
        </div>
      ) : (
        <div ref={listRef} className="flex-1 space-y-3 overflow-y-auto px-4 py-3">
          {msgs.length === 0 && (
            <div className="text-sm text-ink-soft">
              <p>Ask about CLM workflows, business rules, statuses or validation messages — in English or Arabic. On a case, I can tell you exactly what is still blocking it.</p>
              <div className="mt-3 space-y-1.5">
                {suggestedQuestions(ctx, c).map((q) => (
                  <button key={q} type="button" onClick={() => send(q)} dir="auto" className="block w-full rounded-md border border-line px-3 py-2 text-left text-sm hover:bg-surface-sunken">
                    {q}
                  </button>
                ))}
              </div>
            </div>
          )}
          {msgs.map((m) =>
            m.role === 'user' ? (
              <div key={m.id} dir="auto" className="ml-10 rounded-lg bg-ink px-3 py-2 text-sm text-white">
                {m.text}
              </div>
            ) : (
              <AnswerBubble key={m.id} a={m.answer!} onAction={runAction} />
            ),
          )}
          {busy && (
            <div className="flex items-center gap-2 text-xs text-ink-muted">
              <Loader2 className="h-3.5 w-3.5 animate-spin" />
              Searching…
            </div>
          )}
        </div>
      )}

      <form
        className="border-t border-line p-3"
        onSubmit={(e) => {
          e.preventDefault();
          if (article) openAssistant(null);
          void send(text);
        }}
      >
        <div className="flex items-end gap-2 rounded-lg border border-line px-2 py-1.5 focus-within:border-ink/40">
          <textarea
            value={text}
            dir="auto"
            rows={2}
            onChange={(e) => setText(e.target.value)}
            onKeyDown={(e) => {
              if (e.key === 'Enter' && !e.shiftKey) {
                e.preventDefault();
                if (article) openAssistant(null);
                void send(text);
              }
            }}
            placeholder="Ask a question… / اكتب سؤالك"
            aria-label="Ask CLM a question"
            className="max-h-32 flex-1 resize-none text-sm outline-none"
          />
          <button type="submit" disabled={!text.trim() || busy} aria-label="Send question" className="flex h-8 w-8 items-center justify-center rounded-md bg-academy text-white disabled:bg-academy/40">
            <Send className="h-4 w-4" />
          </button>
        </div>
        <p className="mt-1.5 text-2xs text-ink-muted">Training environment. Do not enter real customer data.</p>
      </form>
    </aside>
  );
}

function AnswerBubble({ a, onAction }: { a: AssistantAnswer; onAction: (x: AssistantAction) => void }) {
  return (
    <div className="mr-4 rounded-lg border border-line bg-surface-rail px-3 py-2.5 text-sm">
      {a.status === 'not_found' && (
        <div className="mb-1 flex items-center gap-1 text-xs font-medium text-orange-700">
          <CircleAlert className="h-3.5 w-3.5" />
          Not found in approved documentation
        </div>
      )}
      {a.status === 'unverified' && (
        <div className="mb-1 flex items-center gap-1 text-xs font-medium text-orange-700">
          <CircleAlert className="h-3.5 w-3.5" />
          Part of this topic is still an open question with Product
        </div>
      )}
      <p dir="auto" className="leading-relaxed">
        {a.answer}
      </p>
      {a.points && a.points.length > 0 && (
        <ul className="mt-2 list-disc space-y-1 pl-5 text-ink-soft">
          {a.points.map((p) => (
            <li key={p}>{p}</li>
          ))}
        </ul>
      )}
      {a.actions.length > 0 && (
        <div className="mt-2.5 flex flex-wrap gap-1.5">
          {a.actions.map((x) => (
            <button key={x.label} type="button" onClick={() => onAction(x)} className="flex items-center gap-1 rounded-md border border-academy/30 bg-white px-2 py-1 text-xs font-medium text-academy hover:bg-academy-soft">
              {x.tourId ? <PlayCircle className="h-3 w-3" /> : x.articleId ? <BookOpen className="h-3 w-3" /> : null}
              {x.label}
            </button>
          ))}
        </div>
      )}
      {a.citations.length > 0 && (
        <div className="mt-2.5 border-t border-line pt-2 text-2xs text-ink-muted">
          {a.citations.map((ct) => (
            <div key={ct.articleId} className="flex items-start gap-1">
              <FileText className="mt-0.5 h-3 w-3 shrink-0" />
              <span>
                <span className="font-medium text-ink-soft">{ct.title}</span> · {ct.sources.join('; ')}
              </span>
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
